/** @type {import('tailwindcss').Config} */
function withOpacity(variableName) {
  return ({ opacityValue }) => {
    if (opacityValue !== undefined) {
      return `color-mix(in oklch, var(${variableName}) calc(100% * ${opacityValue}), transparent)`
    }
    return `var(${variableName})`
  }
}

